export function providerLogo(id: AiProviderId, props?: LogoProps) {
  if (id === "opencode") return <OpenCodeLogo {...props} />;
  if (id === "byok-openrouter") return <OpenRouterLogo {...props} />;
  return <OpenRouterLogo {...props} />;
}

/** BYOK curated models: brand marks to showcase compatibility. */
export function modelBrandLogo(modelId: string, props?: LogoProps) {
  const id = modelId.toLowerCase();
  if (id.includes("claude") || id.includes("anthropic")) {
    return <ClaudeLogo {...props} />;
  }
  if (id.includes("gpt") || id.includes("openai") || id.startsWith("openai/")) {
    return <OpenAiLogo {...props} />;
  }
  if (id.includes("deepseek")) {
    return <DeepSeekLogo {...props} />;
  }
  return null;
}
